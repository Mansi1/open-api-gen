// Embeds the hand-written runtime modules (src/emit/runtime/*.ts) as strings, so the published generator can copy
// them into generated clients without reading its own source files. `make lint` fails while the output is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const runtimeDirectory = join(import.meta.dir, "..", "src", "emit", "runtime");
const outputPath = join(runtimeDirectory, "..", "runtime-sources.ts");

const fileNames = readdirSync(runtimeDirectory).filter((fileName) => fileName.endsWith(".ts")).sort();
const entries = fileNames.map((fileName) => {
  const content = readFileSync(join(runtimeDirectory, fileName), "utf8");
  return `  ${JSON.stringify(`runtime/${fileName}`)}: ${JSON.stringify(content)},`;
});
const output = `// Generated by scripts/embed-runtime.ts from src/emit/runtime/. Do not edit; run \`make runtime-sources\`.
export const RUNTIME_SOURCES: Record<string, string> = {
${entries.join("\n")}
};
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== output) {
    console.error("src/emit/runtime-sources.ts is stale: run make runtime-sources");
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, output);
}
